#!/usr/bin/env bash
# Regenerate migrations/baseline/schema.sql: the Bazaar schema at the START of
# module 26 (project/db files 0201 ... 1501, i.e. `reset.sh 26`), as a
# schema-only dump. Revision 2600 executes this file on an empty database.
#
#   ./project/bin/reset.sh 26                                   # the reference state
#   COURSE_PG_CONTAINER=course-pg project/python/migrations/baseline/make_baseline.sh
#
# Run it ONCE, when adopting Alembic, and commit the result. Afterwards the
# file is history: never regenerate it, or databases built from it would
# differ from the ones that were stamped (module 26, section 5).
#
# Cleaning applied to the pg_dump output:
#   * psql meta-commands (\restrict / \unrestrict, PostgreSQL 17.6+) removed:
#     the file is executed through a driver, not psql;
#   * the session-level SETs at the top removed (they would outlive the file on
#     the migration connection, e.g. `SET lock_timeout = 0`), including the empty
#     search_path: every name in the dump is schema-qualified anyway;
#   * CREATE SCHEMA bazaar -> CREATE SCHEMA IF NOT EXISTS bazaar, because
#     env.py creates the schema before Alembic creates bazaar.alembic_version.
set -euo pipefail
CONTAINER="${COURSE_PG_CONTAINER:-course-pg}"
DB="${1:-bazaar}"
OUT="$(cd "$(dirname "$0")" && pwd)/schema.sql"

{
  echo "-- Bazaar baseline schema (state at the start of module 26). Generated by make_baseline.sh."
  echo "-- Do not edit: new changes go into new Alembic revisions."
  docker exec "$CONTAINER" pg_dump -U postgres -d "$DB" --schema-only --no-tablespaces \
    | sed -E \
        -e '/^\\(un)?restrict /d' \
        -e "/^SELECT pg_catalog.set_config\('search_path', '', false\);$/d" \
        -e '/^SET [a-z_]+ = .*;$/d' \
        -e 's/^CREATE SCHEMA bazaar;$/CREATE SCHEMA IF NOT EXISTS bazaar;/'
} > "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
